def denorm_to_uint8(x_norm_chw):
    """
    x_norm_chw: torch.Tensor (3,H,W) normalized
    returns: uint8 numpy array (H,W,3) in [0,255]
    """
    x = x_norm_chw.unsqueeze(0)  # (1,3,H,W)
